// 将 题库/**/*.md（结构化试卷）转换为 exam_papers / exam_sections / exam_questions 三表 INSERT SQL
// 用法: node scripts/md-to-exam-seed.js
// 输出: scripts/seed/04-exam-papers-NN-<examId>.sql (每份试卷一个文件, 与 generate-seed-sql.js 命名一致)
// 之后: 在 Supabase Dashboard → SQL Editor 执行生成的 SQL, 再 npm run fetch:data 同步前端
import fs from 'node:fs';
import path from 'node:path';

const rootDir = path.resolve(process.cwd());
const bankDir = path.resolve(rootDir, '题库');
const outDir = path.resolve(rootDir, 'scripts/seed');
const AUTO_HEADER = '// AUTO-GENERATED by scripts/md-to-exam-seed.js — 题库 md → Supabase seed SQL';

// ─── 工具 ───
function esc(str) {
  if (str === null || str === undefined) return 'NULL';
  return "'" + String(str).replace(/'/g, "''").replace(/\\/g, '\\\\') + "'";
}

function escJson(arr) {
  if (!arr || arr.length === 0) return "'[]'::jsonb";
  return esc(JSON.stringify(arr)) + '::jsonb';
}

// 解析 YAML frontmatter（极简，本格式只有 key: "value" 或 key: value）
function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return {};
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const i = t.indexOf(':');
    if (i === -1) continue;
    let key = t.slice(0, i).trim();
    let value = t.slice(i + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    meta[key] = value;
  }
  return meta;
}

// 解析题目块: "### Q1\n\n- **question_type**: 0\n- **title**: ...\n- **content**: ...\n- **options**:\n  - A. ...\n  - B. ...\n- **answer**: ..."
function parseQuestionBlock(block) {
  const q = { question_type: 0, title: '', content: '', options: [], answer: '', answers: [], solution: '', difficulty: 2, tags: [], source: '' };
  const lines = block.split(/\r?\n/);
  let i = 0;
  while (i < lines.length) {
    const ln = lines[i];
    const m = ln.match(/^-\s+\*\*([a-zA-Z_]+)\*\*:\s?(.*)$/);
    if (!m) { i++; continue; }
    const key = m[1];
    let value = m[2];
    if (key === 'options') {
      // 收集后续 "  - xxx" 行
      const opts = [];
      i++;
      while (i < lines.length && /^\s{2,}-\s+/.test(lines[i])) {
        opts.push(lines[i].replace(/^\s{2,}-\s+/, '').trim());
        i++;
      }
      if (opts.length === 0) opts.push(''); // 空数组占位
      q.options = opts;
      continue;
    }
    if (key === 'content' || key === 'solution') {
      // 值可能跨多行（$$...$$ 块等），累积直到下一个 "- **" 或空选项行
      const parts = [value];
      i++;
      while (i < lines.length && !/^-\s+\*\*/.test(lines[i]) && lines[i].trim() !== '') {
        parts.push(lines[i]);
        i++;
      }
      q[key] = parts.join('\n').trim();
      continue;
    }
    q[key] = value.trim();
    i++;
  }
  // 归一化
  for (const k of ['answer', 'solution']) {
    if (q[k] === '暂无答案' || q[k] === '暂无解析') q[k] = '';
  }
  if (q.answer && q.answers === '') q.answers = [];
  if (q.answers === '') q.answers = [];
  if (typeof q.answers === 'string') {
    try { q.answers = JSON.parse(q.answers); } catch { q.answers = []; }
  }
  if (typeof q.tags === 'string') {
    try { q.tags = JSON.parse(q.tags); } catch { q.tags = []; }
  }
  // 选项去掉 "A. " 前缀（与现有数据一致，前端 radio 自带 A/B/C/D 位置）
  q.options = (q.options || []).map(o => o.replace(/^[A-Ha-h][.．、]\s*/, '').trim());
  q.question_type = Number(q.question_type) || 0;
  q.difficulty = Number(q.difficulty) || 2;
  return q;
}

// 解析一份 md → { meta, sections: [{ title, questions: [...] }] }
function parsePaperFile(filePath) {
  const text = fs.readFileSync(filePath, 'utf-8');
  const meta = parseFrontmatter(text);
  const body = text.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/, '');
  const sections = [];
  // 按 "## 章节" 分块
  const secMatches = [...body.matchAll(/^##\s+(.+?)\s*$/gm)];
  for (let si = 0; si < secMatches.length; si++) {
    const title = secMatches[si][1].trim();
    const start = body.indexOf(secMatches[si][0]) + secMatches[si][0].length;
    const end = si + 1 < secMatches.length ? body.indexOf(secMatches[si + 1][0]) : body.length;
    const secBody = body.slice(start, end);
    const questions = [];
    // 按 "### Q{n}" 分块
    const qMatches = [...secBody.matchAll(/^###\s+Q\d+.*$/gm)];
    for (let qi = 0; qi < qMatches.length; qi++) {
      const qStart = secBody.indexOf(qMatches[qi][0]) + qMatches[qi][0].length;
      const qEnd = qi + 1 < qMatches.length ? secBody.indexOf(qMatches[qi + 1][0]) : secBody.length;
      const block = secBody.slice(qStart, qEnd);
      const q = parseQuestionBlock(block);
      if (q.content || q.title) questions.push(q);
    }
    if (title && questions.length > 0) {
      sections.push({ title, questions });
    }
  }
  return { meta, sections };
}

function questionTypeMap(title) {
  // 章节标题 → question_type（与 parse-mineru-to-exams.py 一致）
  if (/多选/.test(title)) return 1;
  if (/判断/.test(title)) return 5;
  if (/填空/.test(title)) return 2;
  if (/证明/.test(title)) return 4;
  if (/计算|解答|应用/.test(title)) return 3;
  return 0;
}

function main() {
  fs.mkdirSync(outDir, { recursive: true });
  const files = [];
  for (const sub of ['高数', '线代']) {
    const dir = path.join(bankDir, sub);
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).filter(x => x.endsWith('.md'))) {
      files.push(path.join(dir, f));
    }
  }
  files.sort();

  let fileIdx = 2; // 现有 01, 02 已被占用
  const report = [];
  for (const filePath of files) {
    const { meta, sections } = parsePaperFile(filePath);
    if (!meta.id) { report.push(`!! 跳过(无 id): ${path.basename(filePath)}`); continue; }
    fileIdx++;
    const lines = ['BEGIN;'];
    lines.push(AUTO_HEADER);
    // exam_papers
    lines.push(`INSERT INTO public.exam_papers (id, school, college, subject, term, duration) VALUES (${esc(meta.id)}, ${esc(meta.school || '')}, ${esc(meta.college || '')}, ${esc(meta.subject || '')}, ${esc(meta.term || '')}, ${esc(meta.duration || '')}) ON CONFLICT (id) DO UPDATE SET school = EXCLUDED.school, college = EXCLUDED.college, subject = EXCLUDED.subject, term = EXCLUDED.term, duration = EXCLUDED.duration;`);
    let qTotal = 0;
    sections.forEach((sec, sIdx) => {
      const sectionId = `${meta.id}-sec-${sIdx}`;
      lines.push(`INSERT INTO public.exam_sections (id, exam_id, title, order_index) VALUES (${esc(sectionId)}, ${esc(meta.id)}, ${esc(sec.title)}, ${sIdx}) ON CONFLICT (id) DO UPDATE SET exam_id = EXCLUDED.exam_id, title = EXCLUDED.title, order_index = EXCLUDED.order_index;`);
      sec.questions.forEach((q, qIdx) => {
        const qid = `q-${meta.id}-s${sIdx}-${qIdx}`;
        const qtype = questionTypeMap(sec.title);
        // 判断题 options 固定 ["正确","错误"]（md 中已含，此处兜底）
        const options = qtype === 5 && (!q.options || q.options.length !== 2)
          ? ['正确', '错误']
          : (q.options || []);
        lines.push(`INSERT INTO public.exam_questions (id, exam_id, section_id, question_type, title, content, options, answer, answers, blanks, tolerance, unit, solution, hint, test_string, image, difficulty, tags, source, order_index) VALUES (${esc(qid)}, ${esc(meta.id)}, ${esc(sectionId)}, ${qtype}, ${esc(q.title || '')}, ${esc(q.content || '')}, ${escJson(options)}, ${esc(String(q.answer ?? ''))}, ${escJson(Array.isArray(q.answers) ? q.answers : [])}, NULL, NULL, NULL, ${esc(q.solution || '')}, ${esc(q.hint ?? null)}, ${esc(q.test_string ?? null)}, ${esc(q.image ?? null)}, ${q.difficulty || 2}, ${escJson(Array.isArray(q.tags) ? q.tags : [])}, ${esc(q.source || null)}, ${qIdx}) ON CONFLICT (id) DO UPDATE SET exam_id = EXCLUDED.exam_id, section_id = EXCLUDED.section_id, question_type = EXCLUDED.question_type, title = EXCLUDED.title, content = EXCLUDED.content, options = EXCLUDED.options, answer = EXCLUDED.answer, answers = EXCLUDED.answers, blanks = EXCLUDED.blanks, tolerance = EXCLUDED.tolerance, unit = EXCLUDED.unit, solution = EXCLUDED.solution, hint = EXCLUDED.hint, test_string = EXCLUDED.test_string, image = EXCLUDED.image, difficulty = EXCLUDED.difficulty, tags = EXCLUDED.tags, source = EXCLUDED.source, order_index = EXCLUDED.order_index;`);
        qTotal++;
      });
    });
    lines.push('COMMIT;');
    const outName = `04-exam-papers-${String(fileIdx).padStart(2, '0')}-${meta.id}.sql`;
    fs.writeFileSync(path.join(outDir, outName), lines.join('\n'), 'utf-8');
    report.push(`${outName}  (${sections.length} 大题 / ${qTotal} 题)`);
  }

  console.log(report.join('\n'));
  console.log(`\n完成：共生成 ${report.length} 个 seed SQL 文件。`);
  console.log('下一步：在 Supabase Dashboard → SQL Editor 中执行这些 SQL，然后 npm run fetch:data 同步前端。');
}

main();
