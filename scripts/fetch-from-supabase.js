// 从 Supabase 拉取所有内容表，生成 src/data/*.js 静态数据文件
// 用法: node scripts/fetch-from-supabase.js
//
// 输出:
//   src/data/courses.js          — COURSES (课程 → 模块 → 小节 嵌套)
//   src/data/questions.js        — QUESTIONS (字段名 snake_case → camelCase)
//   src/data/theoryContents.js   — THEORY_CONTENTS (含从 items 表反查的 title)
//   src/data/examPapers.js       — EXAM_PAPERS (试卷 → 大题 → 题目 嵌套)
//
// 未配置 Supabase 或表为空时打印警告并以 exit 0 退出，不阻塞构建。

import { createClient } from '@supabase/supabase-js';
import { WebSocket } from 'ws';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const envPath = path.resolve(rootDir, '.env.local');
const dataDir = path.resolve(rootDir, 'src/data');

const AUTO_HEADER = '// AUTO-GENERATED by scripts/fetch-from-supabase.js — DO NOT EDIT MANUALLY';

// ─── 解析 .env.local（不依赖 dotenv，手动 KEY="value" 提取） ───
function loadEnvLocal() {
  if (!fs.existsSync(envPath)) return {};
  const content = fs.readFileSync(envPath, 'utf-8');
  const env = {};
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    // 支持 KEY="value" / KEY='value' / KEY=value 三种形式，剥离两端引号
    if ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

const env = loadEnvLocal();
const supabaseUrl = env.VITE_SUPABASE_URL || process.env.VITE_SUPABASE_URL;
const supabaseKey = env.VITE_SUPABASE_ANON_KEY || process.env.VITE_SUPABASE_ANON_KEY;

if (!supabaseUrl || !supabaseKey) {
  console.warn('⚠ 未配置 VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY，跳过数据拉取。');
  console.warn('  请在 .env.local 中填入 Supabase 配置后重试。');
  process.exit(0);
}

const supabase = createClient(supabaseUrl, supabaseKey, {
  auth: { persistSession: false, autoRefreshToken: false },
  realtime: { enabled: false, transport: WebSocket }
});

// ─── 通用 fetch ───
async function fetchAll(table, orderBy = 'id') {
  const { data, error } = await supabase.from(table).select('*').order(orderBy);
  if (error) throw new Error(`fetch ${table}: ${error.message}`);
  return data || [];
}

// ─── Courses: 课程 → 模块 → 小节 嵌套 ───
async function buildCourses() {
  const [courses, modules, items] = await Promise.all([
    fetchAll('courses', 'id'),
    fetchAll('modules', 'order_index'),
    fetchAll('items', 'order_index')
  ]);

  // items 按 (course_id, module_id) 分组
  const itemsByCourseModule = new Map();
  for (const it of items) {
    const key = `${it.course_id}|${it.module_id}`;
    if (!itemsByCourseModule.has(key)) itemsByCourseModule.set(key, []);
    itemsByCourseModule.get(key).push(it);
  }

  // modules 按 course_id 分组
  const modulesByCourse = new Map();
  for (const m of modules) {
    if (!modulesByCourse.has(m.course_id)) modulesByCourse.set(m.course_id, []);
    modulesByCourse.get(m.course_id).push(m);
  }

  return courses.map(c => ({
    id: c.id,
    title: c.title,
    description: c.description || '',
    requirements: Array.isArray(c.requirements) ? c.requirements : [],
    modules: (modulesByCourse.get(c.id) || []).map(m => ({
      id: m.module_id,
      title: m.title,
      items: (itemsByCourseModule.get(`${c.id}|${m.module_id}`) || []).map(it => {
        // 与现有 courses.js 格式一致：theory 小节带 content，其余仅 id/title/type
        const item = { id: it.id, title: it.title, type: it.type };
        if (it.content) item.content = it.content;
        return item;
      })
    }))
  }));
}

// ─── Questions: 字段名 snake_case → camelCase ───
function mapQuestion(q) {
  const out = {
    id: q.id,
    courseId: q.course_id,
    moduleId: q.module_id,
    itemId: q.item_id,
    questionType: q.question_type,
    title: q.title,
    content: q.content,
    answer: q.answer,
    solution: q.solution,
    hint: q.hint,
    difficulty: q.difficulty,
    tags: Array.isArray(q.tags) ? q.tags : [],
    source: q.source
  };
  // 可选字段仅在非空时写入，保持与现有 questions.js 一致
  if (Array.isArray(q.options) && q.options.length) out.options = q.options;
  if (Array.isArray(q.answers) && q.answers.length) out.answers = q.answers;
  if (q.blanks !== null && q.blanks !== undefined) out.blanks = q.blanks;
  if (q.tolerance !== null && q.tolerance !== undefined) out.tolerance = q.tolerance;
  if (q.unit) out.unit = q.unit;
  if (q.test_string) out.testString = q.test_string;
  if (q.image) out.image = q.image;
  return out;
}

async function buildQuestions() {
  const rows = await fetchAll('questions', 'id');
  return rows.map(mapQuestion);
}

// ─── Theory contents: 关联 items 取 title ───
async function buildTheoryContents() {
  const [theories, items] = await Promise.all([
    fetchAll('theory_contents', 'item_id'),
    fetchAll('items', 'id')
  ]);
  const itemMap = new Map(items.map(it => [it.id, it]));

  return theories.map(t => {
    const item = itemMap.get(t.item_id);
    return {
      id: `${t.item_id}-theory`,
      courseId: t.course_id,
      moduleId: t.module_id,
      itemId: t.item_id,
      title: item?.title || '',
      content: t.content || '',
      examples: Array.isArray(t.examples) ? t.examples : []
    };
  });
}

// ─── Exam papers: 试卷 → 大题 → 题目 嵌套 ───
function mapExamQuestion(q) {
  const out = {
    id: q.id,
    examId: q.exam_id,
    sectionId: q.section_id,
    questionType: q.question_type,
    title: q.title,
    content: q.content,
    answer: q.answer,
    solution: q.solution,
    hint: q.hint,
    difficulty: q.difficulty,
    tags: Array.isArray(q.tags) ? q.tags : [],
    source: q.source,
    orderIndex: q.order_index
  };
  if (Array.isArray(q.options) && q.options.length) out.options = q.options;
  if (Array.isArray(q.answers) && q.answers.length) out.answers = q.answers;
  if (q.blanks !== null && q.blanks !== undefined) out.blanks = q.blanks;
  if (q.tolerance !== null && q.tolerance !== undefined) out.tolerance = q.tolerance;
  if (q.unit) out.unit = q.unit;
  if (q.test_string) out.testString = q.test_string;
  if (q.image) out.image = q.image;
  return out;
}

async function buildExamPapers() {
  const [papers, sections, questions] = await Promise.all([
    fetchAll('exam_papers', 'id'),
    fetchAll('exam_sections', 'order_index'),
    fetchAll('exam_questions', 'order_index')
  ]);

  const questionsBySection = new Map();
  for (const q of questions) {
    if (!questionsBySection.has(q.section_id)) questionsBySection.set(q.section_id, []);
    questionsBySection.get(q.section_id).push(q);
  }

  const sectionsByExam = new Map();
  for (const s of sections) {
    if (!sectionsByExam.has(s.exam_id)) sectionsByExam.set(s.exam_id, []);
    sectionsByExam.get(s.exam_id).push(s);
  }

  return papers.map(p => ({
    id: p.id,
    school: p.school || '',
    college: p.college || '',
    subject: p.subject || '',
    term: p.term || '',
    duration: p.duration,
    sections: (sectionsByExam.get(p.id) || []).map(s => ({
      // 与现有 examPapers.js 一致：大题只保留 title + questions
      title: s.title,
      questions: (questionsBySection.get(s.id) || []).map(mapExamQuestion)
    }))
  }));
}

// ─── 写文件 ───
function writeFile(name, constName, data) {
  const filePath = path.resolve(dataDir, name);
  const serialized = JSON.stringify(data, null, 2);
  const content = `${AUTO_HEADER}\nexport const ${constName} = ${serialized};\n`;
  fs.writeFileSync(filePath, content, 'utf-8');
  console.log(`✓ 写入 ${path.relative(rootDir, filePath)} (${data.length} 项)`);
}

// ─── 主流程 ───
async function main() {
  console.log('从 Supabase 拉取内容数据...\n');
  console.log(`  URL: ${supabaseUrl}\n`);

  if (!fs.existsSync(dataDir)) {
    fs.mkdirSync(dataDir, { recursive: true });
  }

  // 任何表失败都不阻塞其他表，最终 exit 0
  let hasError = false;

  // Courses
  try {
    const courses = await buildCourses();
    if (courses.length === 0) {
      console.warn('⚠ courses 表为空，跳过 courses.js');
    } else {
      writeFile('courses.js', 'COURSES', courses);
    }
  } catch (e) {
    console.error(`✗ courses 失败: ${e.message}`);
    hasError = true;
  }

  // Questions
  try {
    const questions = await buildQuestions();
    if (questions.length === 0) {
      console.warn('⚠ questions 表为空，跳过 questions.js');
    } else {
      writeFile('questions.js', 'QUESTIONS', questions);
    }
  } catch (e) {
    console.error(`✗ questions 失败: ${e.message}`);
    hasError = true;
  }

  // Theory contents
  try {
    const theories = await buildTheoryContents();
    if (theories.length === 0) {
      console.warn('⚠ theory_contents 表为空，跳过 theoryContents.js');
    } else {
      writeFile('theoryContents.js', 'THEORY_CONTENTS', theories);
    }
  } catch (e) {
    console.error(`✗ theory_contents 失败: ${e.message}`);
    hasError = true;
  }

  // Exam papers
  try {
    const papers = await buildExamPapers();
    if (papers.length === 0) {
      console.warn('⚠ exam_papers 表为空，跳过 examPapers.js');
    } else {
      writeFile('examPapers.js', 'EXAM_PAPERS', papers);
    }
  } catch (e) {
    console.error(`✗ exam_papers 失败: ${e.message}`);
    hasError = true;
  }

  console.log('\n完成。');
  if (hasError) {
    console.warn('⚠ 部分表拉取失败，详见上方错误信息（已生成的文件仍有效）。');
  }
  process.exit(0);
}

main().catch(e => {
  console.error('未预期错误:', e);
  process.exit(0);
});
